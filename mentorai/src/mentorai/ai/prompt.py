def clean_mentor_name(value: str) -> str:
    """نام منتور برای گذاشتن در دستور: بدون آکولاد و خط‌جدید، کوتاه."""
    cleaned = re.sub(r"[{}\r\n\t]", " ", value)
    return re.sub(r"\s+", " ", cleaned).strip()[:80] or DEFAULT_MENTOR_NAME


def build_system_prompt(mentor_name: str = "") -> str:
    """دستور سیستمیِ مسیر زنده برای منتورِ یک حساب. نام ناشناخته به «منتور» برمی‌گردد."""
    return SYSTEM_PROMPT_TEMPLATE.replace(MENTOR_PLACEHOLDER, clean_mentor_name(mentor_name))


def _format_sources(hits: Sequence[Hit]) -> str:
    if not hits:
        return "هیچ منبعی برای این سؤال پیدا نشد."
    lines = []
    for hit in hits:
        lines.append(
            f"[id={hit.chunk_id} source={hit.source_class} authority={hit.authority}]\n"
            f"{hit.content}"
        )
    return "\n\n".join(lines)


def build_user_content(
    *,
    question: str,
    hits: Sequence[Hit],
    history: Sequence[tuple[str, str]] = (),
    memories: str = "",
) -> str:
    """بخش متغیر: منابع، حافظه، تاریخچه‌ی کوتاه، و سؤال.

    سؤال آخر می‌آید تا در متن طولانی گم نشود.
    """
    parts = [f"منابع:\n\n{_format_sources(hits)}"]
    if memories:
        parts.append(
            "آنچه از قبل درباره‌ی این دانشجو می‌دانیم. این‌ها زمینه‌اند، نه پاسخ؛ "
            f"محتوای پاسخ همیشه از منابع می‌آید:\n{memories}"
        )
    if history:
        rendered = "\n".join(f"- {role}: {text}" for role, text in history)
        parts.append(f"چند پیام آخر همین مکالمه، فقط برای زمینه:\n{rendered}")
    parts.append(f"سؤال دانشجو:\n{question}")
    return "\n\n---\n\n".join(parts)
